#!/usr/bin/env python3
"""Generate/refresh CHANGELOG.md from git history using Conventional Commits.

Pure standard library. Parses `git log` subjects of the form

    type(scope): description
    type: description

and groups them under the standard headings. Unconventional subjects are
bucketed under "Other".

Usage:
    python3 scripts/generate-changelog.py            # regenerate CHANGELOG.md
    python3 scripts/generate-changelog.py --stdout   # print instead of write
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CHANGELOG_PATH = REPO_ROOT / "CHANGELOG.md"

# Conventional Commit type -> changelog section title
TYPE_SECTIONS: "OrderedDict[str, str]" = OrderedDict(
    [
        ("feat", "Features"),
        ("fix", "Bug Fixes"),
        ("perf", "Performance"),
        ("docs", "Documentation"),
        ("refactor", "Refactoring"),
        ("test", "Tests"),
        ("build", "Build"),
        ("ci", "CI"),
        ("chore", "Chores"),
        ("revert", "Reverts"),
    ]
)
OTHER_SECTION = "Other"

SUBJECT_RE = re.compile(r"^(?P<type>[a-zA-Z]+)(?:\((?P<scope>[^)]*)\))?!?:\s*(?P<desc>.+)$")


def git_log() -> list[tuple[str, str]]:
    """Return (short_hash, subject) pairs, newest first."""
    out = subprocess.run(
        ["git", "log", "--pretty=format:%h%x00%s"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    entries = []
    for line in out.splitlines():
        if "\x00" not in line:
            continue
        short, subject = line.split("\x00", 1)
        entries.append((short.strip(), subject.strip()))
    return entries


def classify(subject: str) -> tuple[str, str | None, str]:
    """Return (type_key, scope, description)."""
    m = SUBJECT_RE.match(subject)
    if not m:
        return OTHER_SECTION, None, subject
    ctype = m.group("type").lower()
    if ctype not in TYPE_SECTIONS:
        return OTHER_SECTION, None, subject
    return ctype, m.group("scope"), m.group("desc")


def render(sections: "OrderedDict[str, list[str]]") -> str:
    lines = [
        "# Changelog",
        "",
        "All notable changes to this project are documented here.",
        "Generated by `scripts/generate-changelog.py` from git history",
        "using [Conventional Commits](https://www.conventionalcommits.org/).",
        "",
        "## [Unreleased]",
        "",
    ]
    for section, items in sections.items():
        if not items:
            continue
        title = TYPE_SECTIONS.get(section, section)
        lines.append(f"### {title}")
        lines.append("")
        lines.extend(items)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stdout", action="store_true", help="print instead of writing CHANGELOG.md")
    args = parser.parse_args()

    sections: "OrderedDict[str, list[str]]" = OrderedDict(
        [(k, []) for k in TYPE_SECTIONS] + [(OTHER_SECTION, [])]
    )
    for short, subject in git_log():
        ctype, scope, desc = classify(subject)
        bullet = f"- **{scope}:** {desc} (`{short}`)" if scope else f"- {desc} (`{short}`)"
        sections[ctype].append(bullet)

    # Drop empty trailing "Other" section if unused
    if not sections[OTHER_SECTION]:
        del sections[OTHER_SECTION]

    text = render(sections)
    if args.stdout:
        sys.stdout.write(text)
    else:
        CHANGELOG_PATH.write_text(text, encoding="utf-8")
        print(f"Wrote {CHANGELOG_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
